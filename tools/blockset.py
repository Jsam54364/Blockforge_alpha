"""The biome block set: every block the 15 biomes need (soils, rocks and their building
blocks, the trees, ores and minerals, and each region's special blocks), painted in the same
manner as tools/paint_textures.py (32 x 32, Vintage Story-like: fine grain and low contrast
for terrain, short hue-shifted ramps lit from the top left for wood and crafted blocks).

    python3 tools/blockset.py            paint the textures, write the block list
    python3 tools/blockset.py --sheet    also write /tmp/blockset_sheet.png (all textures)

It writes:
  * assets/textures/<name>.png for every texture below;
  * the generated part of assets/blocks.toml (after its "generated" line; the part above is
    hand-written and keeps the oldest ids);
  * app/src/texture_files.rs, the list of texture files the game embeds.

Block ids are the order of assets/blocks.toml, so `BLOCKS` below is append-only: add new
blocks at the end of it, never reorder or remove (saved worlds store ids).

Each block has a group (the inventory's tab: building, natural, wood, minerals) and a
family (the material: blocks of one family sit together in the inventory, in the order they
first appear in the file). `slab=True` also makes it a slab in the inventory.
"""
