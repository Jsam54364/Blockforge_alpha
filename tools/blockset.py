def sheet(names):
    from PIL import Image
    cols = 16
    s, pad = 96, 4
    rows = (len(names) + cols - 1) // cols
    out = Image.new('RGB', (cols * (s + pad) + pad, rows * (s + pad) + pad), (30, 30, 30))
    for i, n in enumerate(names):
        im = Image.open(os.path.join(P.OUT, n + '.png')).convert('RGB').resize((s, s), Image.NEAREST)
        out.paste(im, (pad + (i % cols) * (s + pad), pad + (i // cols) * (s + pad)))
    out.save('/tmp/blockset_sheet.png')


