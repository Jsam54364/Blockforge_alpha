def crystal(name, cols):
    """Faceted crystal: Voronoi facets, each lit by which way it faces, bright edges."""
    r = rng(name)
    f1, f2, ids = voronoi(r, 4, jitter=0.95)
    face = (ids * 0.618) % 1.0
    img = lerp_stops(face, cols)
    edge = (f2 - f1) < 0.6
    img = np.where(edge[..., None], np.minimum(np.array(cols[-1]) * 1.15, 1), img)
    img = np.where(specks(r, 0.02)[..., None], C(1, 1, 1), img)
    return img


