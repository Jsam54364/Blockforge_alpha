def fern_tex():
    """Fern fronds: bright, feathery clusters with dark gaps, lit from the top left."""
    r = rng('fern')
    img = np.zeros((N, N, 3))
    base = C(0.08, 0.16, 0.05)
    img[:] = base
    cols = [C(0.18, 0.40, 0.10), C(0.28, 0.54, 0.14), C(0.40, 0.66, 0.20), C(0.56, 0.78, 0.30)]
    for _ in range(9):
        cx, cy = r.integers(0, N, 2)
        a = r.random() * 2 * np.pi
        L = 8 + r.integers(0, 8)
        for k in range(L):
            x = int(cx + np.cos(a) * k) % N
            y = int(cy + np.sin(a) * k) % N
            img[y, x] = cols[1]
            w = int((1 - k / L) * 3) + 1
            for side in (-1, 1):
                for j in range(1, w + 1):
                    px = int(x + np.cos(a + side * 1.2) * j) % N
                    py = int(y + np.sin(a + side * 1.2) * j) % N
                    img[py, px] = cols[min(3, 2 + (side < 0))] if j == 1 else cols[0 + (side < 0)]
    return img


def meadow_top():
    """Greyscale grass (tinted by biome: alpha 0) dotted with flowers in their own colours
    (alpha 255: not tinted)."""
    grey = P.grass_top('meadow_grass', 5, 0.7, 0.55, 0.0)
    rgba = np.zeros((N, N, 4))
    rgba[..., 0] = rgba[..., 1] = rgba[..., 2] = grey * 255
    r = rng('meadow flowers')
    petals = [C(0.95, 0.95, 0.92), C(0.98, 0.86, 0.24), C(0.92, 0.48, 0.70), C(0.62, 0.50, 0.92), C(0.96, 0.40, 0.30)]
    for _ in range(26):
        x, y = r.integers(0, N, 2)
        c = petals[r.integers(0, len(petals))]
        for dx, dy in ((0, 0), (1, 0), (0, 1), (-1, 0), (0, -1)):
            if dx == dy == 0 or r.random() < 0.75:
                px, py = (x + dx) % N, (y + dy) % N
                k = 1.0 if dx == dy == 0 else 0.85
                rgba[py, px, :3] = c * 255 * (0.8 if (dx, dy) == (0, 0) else k)
                rgba[py, px, 3] = 255
        rgba[y, x, :3] = C(0.98, 0.84, 0.30) * 255
    return rgba


def toml_block(name, group, family, tex, kw):
    lines = ['[[block]]', f'name = "{name}"', f'group = "{group}"', f'family = "{family}"']
    for k in ('label', 'biome', 'solid', 'opaque', 'render', 'light', 'hardness', 'behavior', 'slab'):
        if k in kw:
            v = kw[k]
            lines.append(f'{k} = ' + (('true' if v else 'false') if isinstance(v, bool) else (f'"{v}"' if isinstance(v, str) else f'{v}')))
    if isinstance(tex, dict):
        for face in ('top', 'side', 'bottom'):
            if face in tex:
                lines.append(f'{face} = "{tex[face]}"')
    elif tex != name:
        lines.append(f'texture = "{tex}"')
    return '\n'.join(lines)


def write_toml(blocks):
    src = open(TOML).read()
    head = src.split(GEN_MARK)[0].rstrip() + '\n'
    # Group, family and label for the hand-written blocks (added once, kept).
    out = []
    for block in head.split('[[block]]'):
        m = [l for l in block.splitlines() if l.startswith('name = ')]
        if m:
            name = m[0].split('"')[1]
            if name in OLD and 'group = ' not in block:
                g, f, lab = OLD[name]
                extra = f'\ngroup = "{g}"\nfamily = "{f}"' + (f'\nlabel = "{lab}"' if lab else '')
                block = block.replace(m[0], m[0] + extra, 1)
        out.append(block)
    head = '[[block]]'.join(out)
    body = '\n\n'.join(toml_block(*b) for b in blocks)
    with open(TOML, 'w') as f:
        f.write(head.rstrip() + '\n\n' + GEN_MARK + '\n# The 15 biomes\' blocks (see tools/blockset.py for which biome each is for).\n\n' + body + '\n')


