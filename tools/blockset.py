# ------------------------------------------------------------------ crafted stone

def stone_cobble(name, base, mortar=0.35):
    """Cobblestone: rounded stones of the rock, each lit from the top left, in dark mortar."""
    r = rng(name)
    f1, f2, ids = voronoi(r, 5, jitter=0.85)
    edge = np.clip((f2 - f1) / 2.2, 0, 1)
    h = np.sqrt(edge)
    lit = 1.0 + 0.6 * shade(h) + 0.12 * (((ids * 0.618) % 1.0) - 0.5) - 0.1 * (1 - h)
    img = base * lit[..., None]
    img = np.where((edge < 0.2)[..., None], base * mortar * (0.8 + 0.4 * noise(r, 16))[..., None], img)
    return tone(img, 0.015, r)


def stone_bricks(name, base, rows=4, cols=2, mortar=0.42, shift=0.5):
    """Bricks of the rock: courses `rows` high, `cols` bricks across, joints offset."""
    r = rng(name)
    bh, bw = N // rows, N // cols
    row = ys // bh
    off = ((row % 2) * shift * bw).astype(int)
    col = (xs + off) // bw
    ix, iy = (xs + off) % bw, ys % bh
    joint = (ix == 0) | (iy == 0)
    brick_id = row * 7 + col
    vary = ((brick_id * 0.618) % 1.0 - 0.5) * 0.14
    bevel = np.where(iy == 1, 0.12, 0) + np.where(ix == 1, 0.06, 0) - np.where(iy == bh - 1, 0.12, 0) - np.where(ix == bw - 1, 0.06, 0)
    img = base * (1.0 + vary + bevel)[..., None]
    img = np.where(joint[..., None], base * mortar, img)
    chip = specks(r, 0.02) & ~joint
    img = np.where(chip[..., None], img * 0.82, img)
    return tone(img, 0.012, r)


def stone_polished(name, base, border=0.75):
    """Polished stone: the rock smoothed, with a bevelled rim (a slab-cut block)."""
    r = rng(name)
    img = blur(base, 2) * 0.6 + base * 0.4
    m = np.minimum(np.minimum(xs, ys), np.minimum(N - 1 - xs, N - 1 - ys))
    img = np.where((m == 0)[..., None], img * border, img)
    img = np.where(((xs == 1) | (ys == 1))[..., None] & (m == 1)[..., None], img * 1.1, img)
    img = np.where(((xs == N - 2) | (ys == N - 2))[..., None] & (m == 1)[..., None], img * 0.88, img)
    return tone(img, 0.008, r)


def mossy(name, base_img):
    r = rng(name)
