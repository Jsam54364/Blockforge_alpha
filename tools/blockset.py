ORE_COLOURS = {
    'iron': [C(0.42, 0.24, 0.16), C(0.60, 0.38, 0.26), C(0.76, 0.56, 0.42)],
    'copper': [C(0.52, 0.26, 0.12), C(0.74, 0.42, 0.20), C(0.30, 0.62, 0.50)],
    'silver': [C(0.56, 0.58, 0.62), C(0.76, 0.78, 0.82), C(0.95, 0.96, 0.98)],
    'gold': [C(0.62, 0.42, 0.06), C(0.86, 0.66, 0.16), C(0.99, 0.88, 0.42)],
    'ruby': [C(0.42, 0.04, 0.08), C(0.72, 0.08, 0.14), C(0.98, 0.36, 0.40)],
    'sapphire': [C(0.06, 0.12, 0.42), C(0.12, 0.26, 0.74), C(0.44, 0.62, 0.98)],
    'blight': [C(0.26, 0.10, 0.30), C(0.50, 0.18, 0.56), C(0.70, 0.86, 0.30)],
    'coal': [C(0.06, 0.06, 0.07), C(0.12, 0.12, 0.13), C(0.22, 0.22, 0.24)],
}


def ore(name, host_img, kind, clusters=5, gem=False):
    """The host rock with nuggets of the ore (for gems, small faceted crystals): each nugget a
    little lump a few pixels across, lit from the top left, darker where it meets the rock."""
    r = rng(name)
    img = host_img.copy()
    dark, mid, light = ORE_COLOURS[kind]
    for _ in range(clusters):
        cy, cx = r.integers(0, N, 2)
        for _ in range(int(r.integers(2, 4))):
            ny, nx = cy + r.integers(-3, 4), cx + r.integers(-3, 4)
            rad = 1.2 + r.random() * (0.9 if gem else 1.3)
            dy = ((ys - ny + N / 2) % N) - N / 2
            dx = ((xs - nx + N / 2) % N) - N / 2
            d = np.sqrt(dx * dx + dy * dy)
            inside = d < rad
            rim = (d >= rad) & (d < rad + 0.9)
            img = np.where(rim[..., None], img * 0.7, img)
            lit = (dx + dy) < -0.4 * rad
            col = np.where(lit[..., None], light, np.where(((dx + dy) > 0.5 * rad)[..., None], dark, mid))
            img = np.where(inside[..., None], col, img)
            if gem:
                img[int(ny) % N, int(nx) % N] = np.minimum(light * 1.2, 1)
    return img


def fossil():
    img = np.clip(P.limestone(), 0, 1)
    r = rng('fossil')
    # A curled shell (ammonite) and a few bones, pale on the rock.
    cx, cy = 12, 13
    ang = np.arctan2(ys - cy, xs - cx)
    d = np.sqrt((xs - cx) ** 2 + (ys - cy) ** 2)
    spiral = (np.abs(((d - (ang + np.pi) * 1.1) % 3.2) - 1.6) < 0.6) & (d < 8)
    img = np.where(spiral[..., None], C(0.90, 0.86, 0.76), img)
    img = np.where(((np.abs(((d - (ang + np.pi) * 1.1) % 3.2) - 1.6) < 0.9) & (d < 8.5) & ~spiral)[..., None], img * 0.78, img)
    for (y, x, l) in ((24, 18, 9), (27, 4, 6)):
        for k in range(l):
            img[(y + k // 3) % N, (x + k) % N] = C(0.88, 0.84, 0.74)
        img[y % N, (x - 1) % N] = img[(y + 1) % N, (x - 1) % N] = C(0.88, 0.84, 0.74)
    return tone(img, 0.01, r)


def amber():
    r = rng('amber')
    v = 0.6 * fbm(r, 3, 3) + 0.4 * strata(r, 4, 1.5)
    img = lerp_stops(v, [C(0.48, 0.22, 0.03), C(0.70, 0.38, 0.06), C(0.86, 0.56, 0.12), C(0.96, 0.74, 0.28)])
