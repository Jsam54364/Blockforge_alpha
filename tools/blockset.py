def C(*rgb):
    return np.array(rgb, dtype=float)


def blur(img, k=1):
    out = img.copy()
    for _ in range(k):
        out = (out + np.roll(out, 1, 0) + np.roll(out, -1, 0) + np.roll(out, 1, 1) + np.roll(out, -1, 1)) / 5
    return out


def lum(img):
    return img[..., 0] * 0.3 + img[..., 1] * 0.55 + img[..., 2] * 0.15


# ------------------------------------------------------------------ rocks

def rock(name, stops, strata_bands=0, strata_amount=0.0, pits=0.0, light=0.0, cracks=0, grain=0.3, joints=0.0):
    """A natural rock: mottled ramp, optional layers, pits, pale specks, hairline cracks."""
    r = rng(name)
    v = mottle(r, coarse=3, grain=grain)
    if strata_bands:
        v = (1 - strata_amount) * v + strata_amount * strata(r, strata_bands, 0.8)
    img = lerp_stops(v, stops)
    for k in range(cracks):
        path = (r.integers(0, N) + np.cumsum(r.integers(-1, 2, N))) % N
        crack = (xs == path[:, None]) if k % 2 == 0 else (ys == path[None, :])
        crack &= (noise(r, 3) > 0.5) & (r.random((N, N)) < 0.85)
        img = np.where(crack[..., None], img * 0.68, img)
    if joints:
        f1, f2, _ = voronoi(r, 3, jitter=0.7)
        img = np.where(((f2 - f1) < joints)[..., None], img * 0.8, img)
    if pits:
        img = np.where(specks(r, pits, 2)[..., None], img * 0.72, img)
    if light:
        img = np.where(specks(r, light)[..., None], img * 1.18, img)
    return tone(img, 0.018, r)


def slate():
    r = rng('slate')
    # Fine cleavage: thin dark and light sheets, slightly wavy, blue-grey.
    y = ys + 1.2 * (fbm(r, 4, 2) - 0.5) * 4
    sheets = 0.5 + 0.5 * np.sin(y / N * 2 * np.pi * 8 + 2.0 * noise(r, 8))
    v = 0.45 * sheets + 0.55 * mottle(r, coarse=3, grain=0.25)
    img = lerp_stops(v, [C(0.20, 0.22, 0.26), C(0.27, 0.29, 0.33), C(0.33, 0.35, 0.39), C(0.39, 0.41, 0.44)])
    img = np.where(specks(r, 0.02)[..., None], img * 1.2, img)
    return tone(img, 0.012, r)


