def bark_tex(name, hue, sat, dark, light, style):
    r = rng(name)
    n = 6
    ramp_c = ramp(hue, sat, dark, light, n, dark_hue=hue - 12, light_hue=hue + 10)
    if style == 'birch':
        # White bark with dark horizontal lenticels and black patches.
        v = 0.7 + 0.3 * fbm(r, 4, 2)
        idx = np.clip((v * n).astype(int), 3, n - 1)
        for _ in range(14):
            y, x = r.integers(0, N, 2)
            w = int(r.integers(3, 9))
            idx[y % N, [(x + k) % N for k in range(w)]] = int(r.integers(0, 2))
        blot = (fbm(r, 5, 2) > 0.74)
        idx = np.where(blot, 1, idx)
        return ramp_c[idx]
    if style == 'palm':
        # Stacked diamond-shaped leaf scars.
        rowh = 6
        row = ys // rowh
        xx = (xs + (row % 2) * 4) % 8
        yy = ys % rowh
        h = 1 - np.abs(xx - 4) / 4 * 0.6 - yy / rowh * 0.8
        v = 1.4 * shade(h) + 0.5 * h + 0.15 * r.random((N, N))
        idx = quantize(v, n, dither=0.2)
        idx = np.where(yy == rowh - 1, 0, idx)
        return ramp_c[clean(idx)]
    widths, x = [], 0
    lo, hi = {'deep': (2, 5), 'plate': (4, 8), 'scaly': (3, 6)}[style]
    while x < N:
        w = int(r.integers(lo, hi))
        widths.append(min(w, N - x))
        x += w
    col_id = np.repeat(np.arange(len(widths)), widths)[:N]
    pos = np.concatenate([np.linspace(0, 1, w, endpoint=False) for w in widths])[:N]
    xsp, ids = np.tile(pos, (N, 1)), np.tile(col_id, (N, 1))
    breaks = noise(r, 4 if style != 'scaly' else 8)
    period = {'deep': 2, 'plate': 3, 'scaly': 6}[style]
    yv = (ys / N * period + breaks * 2 + ids * 0.37) % 1.0
    h = np.sin(xsp * np.pi) ** 0.6 * 1.2 - (yv < 0.12) * 0.8 + 0.3 * fbm(r, 8, 1)
    v = 1.5 * shade(h) + 0.4 * h + 0.2 * ((ids * 0.618) % 1.0)
    idx = quantize(v, n, dither=0.2)
    idx = np.where(xsp < 0.18, np.minimum(idx, 1), idx)
    return ramp_c[separate(clean(idx), n)]


def log_top_tex(name, bark, wood):
    r = rng(name)
    d = np.sqrt((xs + 0.5 - 16) ** 2 + (ys + 0.5 - 16) ** 2) + 1.2 * (fbm(r, 4, 2) - 0.5)
    wood_c = ramp(wood[0], wood[1], wood[2], wood[3], 5, dark_hue=wood[0] - 10, light_hue=wood[0] + 6)
    bark_c = ramp(bark[0], bark[1], bark[2], bark[3], 4, dark_hue=bark[0] - 12, light_hue=bark[0] + 8)
    ring = (np.floor(d / 2.0) % 2 == 0)
    idx = np.where(ring, 3, 2)
    idx = np.where(d < 1.6, 1, idx)
    crack = (np.abs(np.arctan2(ys - 16, xs - 16) - (r.random() * 6 - 3)) < 0.08) & (d > 3) & (d < 11)
    idx = np.where(crack, 1, idx)
    img = wood_c[idx]
    rim = np.maximum(np.abs(xs + 0.5 - 16), np.abs(ys + 0.5 - 16)) > 13.5
    bark_idx = np.clip((fbm(r, 8, 1) * 4).astype(int), 0, 3)
    return np.where(rim[..., None], bark_c[bark_idx], img)


def planks_tex(name, hue, sat, dark, light, boards=4):
    """Boards running across, each with its own shade and wavy grain, seams and nail heads."""
    r = rng(name)
    n = 5
    c = ramp(hue, sat, dark, light, n, dark_hue=hue - 10, light_hue=hue + 8)
    bh = N // boards
    board = ys // bh
    iy = ys % bh
    seam_x = (r.integers(0, N, boards))
    grain = 0.5 + 0.5 * np.sin((ys * 3.1 + 2.5 * fbm(r, 4, 2) * 6 + xs * 0.05) * 1.2)
    v = 0.55 * grain + 0.25 * ((board * 0.618) % 1.0) + 0.2 * r.random((N, N))
    idx = 1 + quantize(v, n - 2, dither=0.15)
    idx = np.where(iy == 0, 0, idx)                     # gap between boards
    idx = np.where(iy == 1, np.minimum(idx + 1, n - 1), idx)
    idx = np.where(iy == bh - 1, np.maximum(idx - 1, 1), idx)
    for b in range(boards):
        sx = seam_x[b]
        idx[b * bh:(b + 1) * bh, sx] = 0             # butt joint
        for dx in (2, -3):
            idx[b * bh + bh // 2, (sx + dx) % N] = 0  # nails
    return c[clean(idx, keep=(iy == 0))]


def leaves_tex(name, colours, kind):
    """Leaves: clusters lit from the top left. Needles (conifers) in fine, dense tufts."""
    r = rng(name)
    cells, rad0 = {'pine': (14, 1.1), 'spruce': (14, 1.0), 'fir': (13, 1.1), 'cypress': (12, 1.2), 'palm': (8, 1.6),
                   'willow': (10, 1.3), 'birch': (10, 1.4), 'maple': (9, 1.7), 'golden_oak': (9, 1.7), 'blight': (8, 1.5)}.get(kind, (9, 1.7))
    f1, f2, ids = voronoi(r, cells, jitter=0.9, stretch=(1.0, 0.75))
    rad = rad0 + 0.8 * ((ids * 0.618) % 1.0)
    inside = f1 < rad
    h = np.where(inside, 1 - f1 / rad, 0)
    v = 1.6 * shade(h) + 0.6 * h + 0.3 * ((ids * 0.37) % 1.0)
    n = len(colours) + 1
    idx = np.where(inside, 1 + quantize(v, n - 1), 0)
    if kind in ('willow',):
        idx = np.where((xs % 5 == 0) & (r.random((N, N)) < 0.7), np.maximum(idx, 2), idx)   # hanging strands
    idx = separate(clean(idx), n)
    gap = np.array([colours[0] * 0.55])
    cols = np.concatenate([gap, np.array(colours)])
    return cols[idx]


