def thatch(name, stops, across=False):
    r = rng(name)
    img = np.zeros((N, N, 3))
    v = r.random((N, N))
    stroke = np.zeros((N, N))
    for _ in range(260):
        y, x = r.integers(0, N, 2)
        l = int(r.integers(4, 10))
        lvl = r.random()
        for k in range(l):
            yy, xx = ((y + k) % N, x) if not across else (y, (x + k) % N)
            stroke[yy, xx] = lvl
    img = lerp_stops(0.75 * stroke + 0.25 * v, stops)
    band = (ys % 16 == 15) if not across else np.zeros((N, N), bool)
    img = np.where(band[..., None], img * 0.6, img)
    return tone(img, 0.02, r)


