def shingle():
    r = rng('shingle')
    f1, f2, ids = voronoi(r, 7, jitter=0.9, stretch=(1.0, 0.8))
    edge = np.clip((f2 - f1) / 1.8, 0, 1)
    kinds = np.array([C(0.58, 0.57, 0.55), C(0.46, 0.47, 0.49), C(0.66, 0.63, 0.58), C(0.38, 0.39, 0.42), C(0.72, 0.71, 0.68)])
    img = kinds[ids % len(kinds)] * (1.0 + 1.0 * shade(np.sqrt(edge)))[..., None]
    img = np.where((edge < 0.2)[..., None], C(0.62, 0.56, 0.44) * (0.8 + 0.3 * r.random((N, N)))[..., None], img)
    return tone(img, 0.015, r)


def shelly_sand():
    r = rng('shelly_sand')
    img = np.clip(P.sand(), 0, 1) * 0.92 + 0.05
    for _ in range(9):
        y, x = r.integers(0, N, 2)
        c = C(0.95, 0.90, 0.84) if r.random() < 0.6 else C(0.80, 0.62, 0.52)
        for dy, dx in ((0, 0), (0, 1), (1, 0), (1, 1)):
            if r.random() < 0.85:
                img[(y + dy) % N, (x + dx) % N] = c * (1.05 if dy == 0 else 0.85)
    return img


def ice():
    r = rng('ice')
    v = 0.6 * fbm(r, 3, 3) + 0.4 * r.random((N, N)) * 0.4
    img = lerp_stops(v, [C(0.50, 0.66, 0.82), C(0.60, 0.75, 0.89), C(0.70, 0.83, 0.94)])
    for k in range(3):
        path = (r.integers(0, N) + np.cumsum(r.integers(-1, 2, N))) % N
